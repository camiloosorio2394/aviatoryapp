-- ── 2 · Publicaciones, comentarios, votos, confirmaciones y reportes ───────

create table if not exists public.foro_publicaciones (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  categoria text not null references public.foro_categorias (clave),
  titulo text not null check (char_length(titulo) between 8 and 140),
  cuerpo text not null default '' check (char_length(cuerpo) <= 10000),
  aerolinea_id bigint references public.airlines (id),
  ciudad text check (ciudad is null or char_length(ciudad) between 2 and 60),
  anonima boolean not null default false,
  estado text not null default 'publicada' check (estado in ('publicada', 'oculta', 'eliminada')),
  puntos integer not null default 0,
  comentarios integer not null default 0,
  confirmaciones integer not null default 0,
  desmentidos integer not null default 0,
  reportes integer not null default 0,
  creada_en timestamptz not null default now(),
  editada_en timestamptz,
  actividad_en timestamptz not null default now(),
  -- Solo los avisos: hasta cuándo se dan por vigentes. Confirmar lo alarga.
  vigente_hasta timestamptz,
  constraint foro_aviso_con_aerolinea check (categoria <> 'avisos' or aerolinea_id is not null)
);
create index if not exists foro_publicaciones_estado_idx on public.foro_publicaciones (estado, creada_en desc);
create index if not exists foro_publicaciones_categoria_idx on public.foro_publicaciones (categoria, estado, creada_en desc);
create index if not exists foro_publicaciones_user_idx on public.foro_publicaciones (user_id);
create index if not exists foro_publicaciones_aerolinea_idx on public.foro_publicaciones (aerolinea_id);
