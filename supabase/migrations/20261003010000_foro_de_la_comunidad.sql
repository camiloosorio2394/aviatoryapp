-- Con tres reportes de pilotos distintos se oculta hasta que alguien lo
-- revise. Devuelve si el reporte contó (el mismo piloto no cuenta dos veces).
create or replace function public.foro_reportar(
  p_publicacion bigint,
  p_comentario bigint,
  p_motivo text,
  p_detalle text default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_yo uuid := auth.uid();
  v_detalle text := nullif(btrim(coalesce(p_detalle, '')), '');
  v_dueno uuid;
  v_publicacion bigint;
  v_contado integer;
  v_estado text;
begin
  if v_yo is null then
    raise exception 'sin_sesion' using errcode = '42501';
  end if;
  if num_nonnulls(p_publicacion, p_comentario) <> 1 then
    raise exception 'reporte_invalido' using errcode = '22023';
  end if;
  if p_motivo is null or p_motivo not in ('spam', 'ofensivo', 'falso', 'datos_personales', 'otro') then
    raise exception 'motivo_invalido' using errcode = '22023';
  end if;
  if v_detalle is not null and char_length(v_detalle) > 500 then
    raise exception 'detalle_invalido' using errcode = '22023';
  end if;

  if p_publicacion is not null then
    select user_id into v_dueno from public.foro_publicaciones
    where id = p_publicacion and estado = 'publicada' for update;
    if not found then
      raise exception 'no_encontrada' using errcode = 'P0002';
    end if;
    if v_dueno = v_yo then
      raise exception 'reporte_propio' using errcode = '22023';
    end if;
    insert into public.foro_reportes (user_id, publicacion_id, motivo, detalle)
    values (v_yo, p_publicacion, p_motivo, v_detalle)
    on conflict do nothing;
    get diagnostics v_contado = row_count;
    if v_contado = 1 then
      update public.foro_publicaciones
      set reportes = reportes + 1, estado = case when reportes + 1 >= 3 then 'oculta' else estado end
      where id = p_publicacion;
    end if;
  else
    select c.user_id, c.publicacion_id into v_dueno, v_publicacion from public.foro_comentarios c
    where c.id = p_comentario and c.estado = 'publicado' for update;
    if not found then
      raise exception 'comentario_no_encontrado' using errcode = 'P0002';
    end if;
    if v_dueno = v_yo then
      raise exception 'reporte_propio' using errcode = '22023';
    end if;
    insert into public.foro_reportes (user_id, comentario_id, motivo, detalle)
    values (v_yo, p_comentario, p_motivo, v_detalle)
    on conflict do nothing;
    get diagnostics v_contado = row_count;
    if v_contado = 1 then
      update public.foro_comentarios
      set reportes = reportes + 1, estado = case when reportes + 1 >= 3 then 'oculto' else estado end
      where id = p_comentario
      returning estado into v_estado;
      -- Estaba publicado (se leyó así arriba): si ahora está oculto, deja de
      -- contar en la publicación.
      if v_estado = 'oculto' then
        update public.foro_publicaciones set comentarios = greatest(comentarios - 1, 0) where id = v_publicacion;
      end if;
    end if;
  end if;
  return v_contado = 1;
end
$$;

