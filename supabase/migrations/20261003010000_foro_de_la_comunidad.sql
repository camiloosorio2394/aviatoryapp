  cuerpo text not null check (char_length(cuerpo) between 1 and 5000),
  anonimo boolean not null default false,
  estado text not null default 'publicado' check (estado in ('publicado', 'oculto', 'eliminado')),
  puntos integer not null default 0,
  reportes integer not null default 0,
  creado_en timestamptz not null default now()
);
create index if not exists foro_comentarios_publicacion_idx on public.foro_comentarios (publicacion_id, creado_en);
create index if not exists foro_comentarios_user_idx on public.foro_comentarios (user_id);
create index if not exists foro_comentarios_padre_idx on public.foro_comentarios (padre_id);
alter table public.foro_comentarios enable row level security;

create table if not exists public.foro_votos (
  publicacion_id bigint not null references public.foro_publicaciones (id) on delete cascade,
