create or replace function public.foro_publicar(
  p_categoria text,
  p_titulo text,
  p_cuerpo text default '',
  p_aerolinea bigint default null,
  p_ciudad text default null,
  p_anonima boolean default false
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_yo uuid := auth.uid();
  v_titulo text := btrim(coalesce(p_titulo, ''));
  v_cuerpo text := btrim(coalesce(p_cuerpo, ''));
  v_ciudad text := nullif(btrim(coalesce(p_ciudad, '')), '');
  v_id bigint;
begin
  if v_yo is null then
    raise exception 'sin_sesion' using errcode = '42501';
  end if;
  if not exists (select 1 from public.foro_categorias where clave = p_categoria) then
    raise exception 'categoria_invalida' using errcode = '22023';
  end if;
  if char_length(v_titulo) < 8 or char_length(v_titulo) > 140 then
    raise exception 'titulo_invalido' using errcode = '22023';
  end if;
  if char_length(v_cuerpo) > 10000 then
    raise exception 'cuerpo_invalido' using errcode = '22023';
  end if;
  if p_categoria = 'avisos' and p_aerolinea is null then
    raise exception 'aviso_sin_aerolinea' using errcode = '22023';
  end if;
  if p_aerolinea is not null and not exists (select 1 from public.airlines where id = p_aerolinea) then
    raise exception 'aerolinea_invalida' using errcode = '22023';
  end if;
  if v_ciudad is not null and char_length(v_ciudad) not between 2 and 60 then
    raise exception 'ciudad_invalida' using errcode = '22023';
  end if;

  insert into public.foro_publicaciones (user_id, categoria, titulo, cuerpo, aerolinea_id, ciudad, anonima, puntos, vigente_hasta)
  values (
    v_yo, p_categoria, v_titulo, v_cuerpo, p_aerolinea, v_ciudad, coalesce(p_anonima, false), 1,
    case when p_categoria = 'avisos' then now() + interval '30 days' end
  )
  returning id into v_id;

  -- Como en Reddit, la publicación nace con el voto de quien la escribe.
  insert into public.foro_votos (publicacion_id, user_id, valor) values (v_id, v_yo, 1);
  perform private.foro_primer_paso(v_yo);
  return v_id;
end
$$;

