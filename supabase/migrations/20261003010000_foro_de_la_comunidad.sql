create or replace function public.foro_votar(p_publicacion bigint, p_valor integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_yo uuid := auth.uid();
  v_antes integer;
  v_puntos integer;
begin
  if v_yo is null then
    raise exception 'sin_sesion' using errcode = '42501';
  end if;
  if p_valor is null or p_valor not in (-1, 0, 1) then
    raise exception 'voto_invalido' using errcode = '22023';
  end if;
  -- El candado sobre la publicación ordena los votos que llegan a la vez:
  -- el contador se mueve por diferencia y no se pierde ninguno.
  perform 1 from public.foro_publicaciones where id = p_publicacion and estado = 'publicada' for update;
  if not found then
    raise exception 'no_encontrada' using errcode = 'P0002';
  end if;

  select valor into v_antes from public.foro_votos where publicacion_id = p_publicacion and user_id = v_yo;
  v_antes := coalesce(v_antes, 0);
  if p_valor = 0 and v_antes <> 0 then
    delete from public.foro_votos where publicacion_id = p_publicacion and user_id = v_yo;
  elsif p_valor <> 0 and v_antes = 0 then
    insert into public.foro_votos (publicacion_id, user_id, valor) values (p_publicacion, v_yo, p_valor);
  elsif p_valor <> 0 and p_valor <> v_antes then
    update public.foro_votos set valor = p_valor, creado_en = now()
    where publicacion_id = p_publicacion and user_id = v_yo;
  end if;

  update public.foro_publicaciones set puntos = puntos + (p_valor - v_antes)
  where id = p_publicacion
  returning puntos into v_puntos;
  return jsonb_build_object('puntos', v_puntos, 'mi_voto', p_valor);
end
$$;

-- «¿Sigue vigente?»: sí, ya no, o nulo para retirar lo que dijo.
create or replace function public.foro_confirmar(p_publicacion bigint, p_sigue boolean)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_yo uuid := auth.uid();
  v_p public.foro_publicaciones;
  v_antes boolean;
begin
  if v_yo is null then
    raise exception 'sin_sesion' using errcode = '42501';
  end if;
  select * into v_p from public.foro_publicaciones where id = p_publicacion and estado = 'publicada' for update;
  if not found then
    raise exception 'no_encontrada' using errcode = 'P0002';
  end if;
  if v_p.categoria <> 'avisos' then
    raise exception 'no_es_aviso' using errcode = '22023';
  end if;
  if v_p.user_id = v_yo then
    raise exception 'aviso_propio' using errcode = '22023';
  end if;

  select sigue into v_antes from public.foro_confirmaciones where publicacion_id = p_publicacion and user_id = v_yo;
  if p_sigue is null then
    delete from public.foro_confirmaciones where publicacion_id = p_publicacion and user_id = v_yo;
  elsif v_antes is null then
    insert into public.foro_confirmaciones (publicacion_id, user_id, sigue) values (p_publicacion, v_yo, p_sigue);
  elsif v_antes <> p_sigue then
    update public.foro_confirmaciones set sigue = p_sigue, creada_en = now()
    where publicacion_id = p_publicacion and user_id = v_yo;
  end if;

  update public.foro_publicaciones
  set
    confirmaciones = confirmaciones + (case when p_sigue then 1 else 0 end) - (case when v_antes then 1 else 0 end),
    desmentidos = desmentidos + (case when p_sigue = false then 1 else 0 end) - (case when v_antes = false then 1 else 0 end),
    vigente_hasta = case when p_sigue then greatest(coalesce(vigente_hasta, now()), now() + interval '30 days') else vigente_hasta end,
    actividad_en = now()
  where id = p_publicacion
  returning * into v_p;

  return jsonb_build_object(
    'confirmaciones', v_p.confirmaciones,
    'desmentidos', v_p.desmentidos,
    'vigente', coalesce(v_p.vigente_hasta > now(), false) and not (v_p.desmentidos >= 3 and v_p.desmentidos > v_p.confirmaciones),
    'mi_confirmacion', p_sigue
  );
end
$$;

create or replace function public.foro_comentar(
  p_publicacion bigint,
  p_cuerpo text,
  p_padre bigint default null,
  p_anonimo boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_yo uuid := auth.uid();
  v_cuerpo text := btrim(coalesce(p_cuerpo, ''));
  v_p public.foro_publicaciones;
  v_padre public.foro_comentarios;
  v_c public.foro_comentarios;
begin
  if v_yo is null then
    raise exception 'sin_sesion' using errcode = '42501';
  end if;
  if char_length(v_cuerpo) < 1 or char_length(v_cuerpo) > 5000 then
    raise exception 'comentario_invalido' using errcode = '22023';
  end if;
  select * into v_p from public.foro_publicaciones where id = p_publicacion and estado = 'publicada' for update;
  if not found then
    raise exception 'no_encontrada' using errcode = 'P0002';
  end if;

  if p_padre is not null then
    select * into v_padre from public.foro_comentarios
    where id = p_padre and publicacion_id = p_publicacion and estado = 'publicado';
    if not found then
      raise exception 'comentario_no_encontrado' using errcode = 'P0002';
    end if;
    -- Dos niveles: la respuesta a una respuesta cuelga del mismo raíz.
    if v_padre.padre_id is not null then
      select * into v_padre from public.foro_comentarios where id = v_padre.padre_id;
    end if;
  end if;

  insert into public.foro_comentarios (publicacion_id, user_id, padre_id, cuerpo, anonimo)
  values (p_publicacion, v_yo, v_padre.id, v_cuerpo, coalesce(p_anonimo, false))
  returning * into v_c;

  update public.foro_publicaciones set comentarios = comentarios + 1, actividad_en = now()
  where id = p_publicacion;

  perform private.foro_avisar(v_p.user_id, v_yo, 'Comentaron tu publicación', v_p.titulo, v_p.id);
  if v_padre.id is not null and v_padre.user_id <> v_p.user_id then
    perform private.foro_avisar(v_padre.user_id, v_yo, 'Respondieron tu comentario', v_p.titulo, v_p.id);
  end if;
  perform private.foro_primer_paso(v_yo);

  return private.foro_comentario(v_c, v_yo, case when v_p.anonima then null else v_p.user_id end);
end
$$;

