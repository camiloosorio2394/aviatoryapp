-- ── 5 · Leer: con o sin sesión ─────────────────────────────────────────────

create or replace function public.foro_feed(
  p_categoria text default null,
  p_orden text default 'tendencia',
  p_aerolinea bigint default null,
  p_pagina integer default 0
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_yo uuid := auth.uid();
  v_por_pagina constant integer := 20;
  v_filas jsonb;
  v_hay_mas boolean;
begin
  if p_orden is null or p_orden not in ('tendencia', 'nuevo', 'top') then
    raise exception 'orden_invalido' using errcode = '22023';
  end if;
  if p_pagina is null or p_pagina < 0 or p_pagina > 50 then
    raise exception 'pagina_invalida' using errcode = '22023';
  end if;

  -- Sin sesión se ve la primera página: para seguir hay que entrar.
  if v_yo is null and p_pagina > 0 then
    return jsonb_build_object('publicaciones', '[]'::jsonb, 'hay_mas', false, 'requiere_sesion', true);
  end if;

  with pagina as (
    select
      p.id,
      p.creada_en,
      case p_orden
        when 'tendencia' then private.foro_calor(p.puntos, p.comentarios, p.confirmaciones, p.creada_en)
        when 'top' then p.puntos::double precision
      end as clave
    from public.foro_publicaciones p
    where p.estado = 'publicada'
      and (p_categoria is null or p.categoria = p_categoria)
      and (p_aerolinea is null or p.aerolinea_id = p_aerolinea)
      and (p_orden = 'nuevo' or p.creada_en > now() - interval '90 days')
      and (p_orden <> 'top' or p.creada_en > now() - interval '30 days')
    order by clave desc nulls last, p.creada_en desc, p.id desc
    limit v_por_pagina + 1
    offset p_pagina * v_por_pagina
  ),
  numerada as (
    select id, row_number() over (order by clave desc nulls last, creada_en desc, id desc) as n
    from pagina
  )
  select
    coalesce(jsonb_agg(private.foro_tarjeta(p, v_yo, false) order by nu.n) filter (where nu.n <= v_por_pagina), '[]'::jsonb),
    count(*) > v_por_pagina
  into v_filas, v_hay_mas
  from numerada nu
  join public.foro_publicaciones p on p.id = nu.id;

  return jsonb_build_object(
    'publicaciones', v_filas,
    'hay_mas', v_hay_mas and v_yo is not null,
    'requiere_sesion', v_yo is null and v_hay_mas
  );
end
$$;

create or replace function public.foro_publicacion(p_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_yo uuid := auth.uid();
  v_p public.foro_publicaciones;
  v_autor uuid;
  v_comentarios jsonb;
  v_total integer;
begin
  select * into v_p from public.foro_publicaciones where id = p_id;
  -- La oculta la sigue viendo su autor, con el aviso de que está en revisión.
  if not found or v_p.estado = 'eliminada' or (v_p.estado = 'oculta' and v_p.user_id is distinct from v_yo) then
    return null;
  end if;
  v_autor := case when v_p.anonima then null else v_p.user_id end;

  select count(*) into v_total
  from public.foro_comentarios c
  where c.publicacion_id = p_id and c.estado = 'publicado';

  if v_yo is null then
    -- Sin sesión: los tres comentarios con más puntos, sin sus respuestas.
    select coalesce(jsonb_agg(private.foro_comentario(s.c, null, v_autor) order by (s.c).puntos desc, (s.c).creado_en), '[]'::jsonb)
    into v_comentarios
    from (
      select c
      from public.foro_comentarios c
      where c.publicacion_id = p_id and c.estado = 'publicado' and c.padre_id is null
      order by c.puntos desc, c.creado_en
      limit 3
    ) s;
  else
    -- Con sesión, todos. Un comentario eliminado se queda como hueco si tiene
    -- respuestas, para que la conversación no quede colgando.
    select coalesce(jsonb_agg(private.foro_comentario(s.c, v_yo, v_autor) order by (s.c).creado_en), '[]'::jsonb)
    into v_comentarios
    from (
      select c
      from public.foro_comentarios c
      where c.publicacion_id = p_id
        and (
          c.estado = 'publicado'
          or exists (
            select 1 from public.foro_comentarios r
            where r.padre_id = c.id and r.estado = 'publicado'
          )
        )
      order by c.creado_en
      limit 500
    ) s;
  end if;

  return jsonb_build_object(
    'publicacion', private.foro_tarjeta(v_p, v_yo, true),
    'comentarios', v_comentarios,
    'total_comentarios', v_total,
    'requiere_sesion', v_yo is null
  );
end
$$;

create or replace function public.foro_tendencias()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'categorias', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'clave', c.clave,
        'nombre', c.nombre,
        'descripcion', c.descripcion,
        'semana', (
          select count(*) from public.foro_publicaciones p
          where p.categoria = c.clave and p.estado = 'publicada' and p.creada_en > now() - interval '7 days'
        )
      ) order by c.orden), '[]'::jsonb)
      from public.foro_categorias c
    ),
    'aerolineas', (
      select coalesce(jsonb_agg(t.fila order by t.n desc, t.fila ->> 'nombre'), '[]'::jsonb)
      from (
        select
          jsonb_build_object('id', a.id, 'nombre', a.name, 'codigo', a.code, 'color', a.brand_color, 'publicaciones', count(*)) as fila,
          count(*) as n
        from public.foro_publicaciones p
        join public.airlines a on a.id = p.aerolinea_id
        where p.estado = 'publicada' and p.creada_en > now() - interval '30 days'
        group by a.id
        order by count(*) desc, a.name
        limit 8
      ) t
    ),
    'avisos', (
      select coalesce(jsonb_agg(private.foro_tarjeta(v.p, auth.uid(), false) order by (v.p).creada_en desc), '[]'::jsonb)
      from (
        select p
        from public.foro_publicaciones p
        where p.categoria = 'avisos' and p.estado = 'publicada' and p.vigente_hasta > now()
          and not (p.desmentidos >= 3 and p.desmentidos > p.confirmaciones)
        order by p.creada_en desc
        limit 5
      ) v
    )
  )
$$;

