-- ── 4 · Cómo sale cada cosa (privadas) ─────────────────────────────────────

-- El autor tal como se muestra: usuario, foto y racha. Nunca el id.
create or replace function private.foro_autor(p_user uuid, p_anonimo boolean)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select case when p_anonimo then null else (
    select jsonb_build_object('usuario', p.username, 'foto', p.photo_url, 'racha', coalesce(s.current_streak, 0))
    from public.profiles p
    left join public.streaks s on s.user_id = p.id
    where p.id = p_user
  ) end
$$;

-- Lo que sube una publicación en «Tendencia»: puntos, comentarios y
-- confirmaciones, divididos por la edad. La fórmula de Hacker News, con los
-- comentarios pesando doble porque en un foro de ayuda la conversación es lo
-- que vale.
create or replace function private.foro_calor(p_puntos integer, p_comentarios integer, p_confirmaciones integer, p_creada timestamptz)
returns double precision
language sql
stable
set search_path = ''
as $$
  select (greatest(p_puntos, 0) + 2 * p_comentarios + p_confirmaciones + 1)::double precision
    / power(extract(epoch from (now() - p_creada)) / 3600.0 + 2, 1.5)
$$;

create or replace function private.foro_tarjeta(p public.foro_publicaciones, p_yo uuid, p_completa boolean)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', p.id,
    'categoria', p.categoria,
    'titulo', p.titulo,
    'cuerpo', case when p_completa then p.cuerpo else left(p.cuerpo, 280) end,
    'recortado', not p_completa and char_length(p.cuerpo) > 280,
    'aerolinea', (
      select jsonb_build_object('id', a.id, 'nombre', a.name, 'codigo', a.code, 'color', a.brand_color)
      from public.airlines a where a.id = p.aerolinea_id
    ),
    'ciudad', p.ciudad,
    'autor', private.foro_autor(p.user_id, p.anonima),
    'anonima', p.anonima,
    'puntos', p.puntos,
    'comentarios', p.comentarios,
    'confirmaciones', p.confirmaciones,
    'desmentidos', p.desmentidos,
    'vigente', case when p.categoria = 'avisos' then
      coalesce(p.vigente_hasta > now(), false) and not (p.desmentidos >= 3 and p.desmentidos > p.confirmaciones)
    end,
    'estado', p.estado,
    'creada_en', p.creada_en,
    'editada_en', p.editada_en,
    'mi_voto', case when p_yo is null then 0 else coalesce((
      select v.valor from public.foro_votos v where v.publicacion_id = p.id and v.user_id = p_yo
    ), 0) end,
    'mi_confirmacion', case when p_yo is null then null else (
      select c.sigue from public.foro_confirmaciones c where c.publicacion_id = p.id and c.user_id = p_yo
    ) end,
    'es_mia', p_yo is not null and p.user_id = p_yo
  )
$$;

-- p_autor_publicacion va nulo si la publicación es anónima: marcar «autor» en
-- un comentario con nombre delataría quién escribió la publicación.
create or replace function private.foro_comentario(c public.foro_comentarios, p_yo uuid, p_autor_publicacion uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', c.id,
    'padre_id', c.padre_id,
    'cuerpo', case when c.estado = 'publicado' then c.cuerpo else '' end,
    'estado', c.estado,
    'autor', case when c.estado = 'publicado' then private.foro_autor(c.user_id, c.anonimo) end,
    'es_del_autor', c.estado = 'publicado' and not c.anonimo and p_autor_publicacion is not null
      and c.user_id = p_autor_publicacion,
    'puntos', c.puntos,
    'creado_en', c.creado_en,
    'mi_voto', case when p_yo is null then 0 else coalesce((
      select v.valor from public.foro_votos_comentario v where v.comentario_id = c.id and v.user_id = p_yo
    ), 0) end,
    'es_mio', p_yo is not null and c.user_id = p_yo
  )
$$;

-- Un aviso por publicación mientras no lo lea: diez comentarios seguidos no
-- son diez campanas.
create or replace function private.foro_avisar(p_destino uuid, p_autor uuid, p_titulo text, p_cuerpo text, p_publicacion bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_url text := '/app/comunidad/p/' || p_publicacion;
begin
  if p_destino is null or p_destino = p_autor then
    return;
  end if;
  if exists (
    select 1 from public.notifications n
    where n.user_id = p_destino and n.type = 'foro_respuesta' and n.action_url = v_url and n.read_at is null
  ) then
    return;
  end if;
  insert into public.notifications (user_id, type, title, body, icon, action_url)
  values (p_destino, 'foro_respuesta', p_titulo, left(p_cuerpo, 140), '💬', v_url);
end
$$;

