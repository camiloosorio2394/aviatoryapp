-- ── 4 · Tamaño y forma de lo que escribe el cliente ────────────────────────

alter table public.user_icao_speaking drop constraint if exists user_icao_speaking_tamanos;
alter table public.user_icao_speaking add constraint user_icao_speaking_tamanos check (
  (transcript is null or char_length(transcript) <= 5000)
  and (question_id is null or char_length(question_id) <= 100)
  and (motor is null or char_length(motor) <= 40)
) not valid;

alter table public.user_icao_mock_results drop constraint if exists user_icao_mock_results_scores_tamano;
alter table public.user_icao_mock_results add constraint user_icao_mock_results_scores_tamano
  check (scores is null or pg_column_size(scores) <= 20000) not valid;

alter table public.pilot_state drop constraint if exists pilot_state_licenses_tamano;
alter table public.pilot_state add constraint pilot_state_licenses_tamano
  check (licenses is null or pg_column_size(licenses) <= 20000) not valid;

alter table public.content_reports drop constraint if exists content_reports_contexto_tamano;
alter table public.content_reports add constraint content_reports_contexto_tamano
  check (contexto is null or pg_column_size(contexto) <= 20000) not valid;

-- Una reacción es un emoji, no un texto: hasta 16 caracteres cubre las
-- secuencias con modificadores de tono y las banderas.
alter table public.community_reactions drop constraint if exists community_reactions_emoji_corto;
alter table public.community_reactions add constraint community_reactions_emoji_corto
  check (char_length(emoji) between 1 and 16) not valid;

-- La evidencia de una verificación vive en la carpeta del piloto que la pide.
alter table public.verificaciones_horas drop constraint if exists verificaciones_horas_evidencia_propia;
alter table public.verificaciones_horas add constraint verificaciones_horas_evidencia_propia
  check (evidencia is null or split_part(evidencia, '/', 1) = user_id::text) not valid;

-- La foto de perfil es la del propio piloto en el bucket de avatars, que es la
-- única que la app sube. La CSP ya bloqueaba otras; esto lo dice la base.
alter table public.profiles drop constraint if exists profiles_photo_url_propia;
alter table public.profiles add constraint profiles_photo_url_propia
  check (photo_url is null or photo_url like '%/storage/v1/object/public/avatars/' || id::text || '/%') not valid;

-- ── 5 · Cupo de archivos por piloto ────────────────────────────────────────

drop policy if exists "avatars_authenticated_upload" on storage.objects;
create policy "avatars_authenticated_upload"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'avatars'
    and (select auth.uid())::text = (storage.foldername(name))[1]
    and (
      select count(*) from storage.objects o
      where o.bucket_id = 'avatars' and (storage.foldername(o.name))[1] = (select auth.uid())::text
    ) < 10
  );

drop policy if exists "bitacoras_sube_lo_suyo" on storage.objects;
create policy "bitacoras_sube_lo_suyo"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'bitacoras'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and (
      select count(*) from storage.objects o
      where o.bucket_id = 'bitacoras' and (storage.foldername(o.name))[1] = (select auth.uid())::text
    ) < 300
  );
