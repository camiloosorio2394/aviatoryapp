-- ============================================================================
-- Topes que no se esquivan borrando, topes para lo que no tenía, y límites de
-- tamaño a lo que escribe el cliente.
--
-- Viene de la auditoría de prelanzamiento del 26-sep-2026:
--   · El tope de mensajes y reacciones contaba las filas que EXISTEN en la
--     ventana: el piloto conserva DELETE sobre las suyas, así que publicar y
--     borrar en bucle lo dejaba en cero (y cada mensaje sale por Realtime a
--     todos los del canal).
--   · Postulaciones, vuelos, licencias, respuestas habladas, simulacros ICAO y
--     verificaciones de horas no tenían tope de filas; varios textos y jsonb no
--     tenían tope de tamaño; los archivos de Storage no tenían cupo por piloto.
--   · La reacción aceptaba cualquier texto como emoji, la evidencia de una
--     verificación podía apuntar al archivo de otro piloto, y photo_url
--     aceptaba cualquier URL.
--
-- Qué hace:
--   1. private.registro_de_inserciones: una fila por inserción con tope, que el
--      piloto no puede borrar. El tope cuenta ahí, no en la tabla. Cada
--      inserción poda las filas del mismo piloto y tabla que ya salieron de la
--      ventana, así que el registro no crece sin fin.
--   2. private.insercion_con_tope() cuenta en ese registro. Con un tercer
--      argumento 'sin_fecha' no toca created_at, para las tablas que no lo
--      tienen o lo llaman distinto.
--   3. Topes nuevos (por piloto): postulaciones 30/día, vuelos 100/día,
--      licencias 30/día, respuestas habladas 200/día, simulacros ICAO 20/día,
--      verificaciones de horas 5/día.
--   4. Restricciones de tamaño y forma, NOT VALID: se exigen desde ya a lo
--      nuevo y no fallan por lo que ya hubiera. Comprobado el 26-sep: no hay
--      filas que las violen (0 fotos, 0 reacciones, 0 verificaciones; 2
--      respuestas habladas de 40 caracteres), así que se pueden validar luego
--      con VALIDATE CONSTRAINT.
--   5. Cupo de archivos por piloto: 10 en avatars, 300 en bitacoras.
--
-- NO SE HA APLICADO. Va DESPUÉS de 20261002000000. No borra filas del piloto.
-- Prueba: supabase/tests/topes_y_restricciones.sql.
-- ============================================================================

-- ── 1 · El registro que no se borra ────────────────────────────────────────

create table if not exists private.registro_de_inserciones (
  id bigint generated by default as identity primary key,
  tabla text not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  en timestamptz not null default now()
);
create index if not exists registro_de_inserciones_idx
  on private.registro_de_inserciones (user_id, tabla, en desc);
alter table private.registro_de_inserciones enable row level security;
revoke all on table private.registro_de_inserciones from public, anon, authenticated;

-- ── 2 · El tope, contado en el registro ────────────────────────────────────

create or replace function private.insercion_con_tope()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_maximo int := tg_argv[0]::int;
  v_ventana interval := tg_argv[1]::interval;
  v_con_fecha boolean := tg_nargs < 3 or tg_argv[2] <> 'sin_fecha';
  v_recientes int;
begin
  -- La fecha la pone el servidor: nada de mensajes fechados en el futuro.
  if v_con_fecha then
    new.created_at := now();
  end if;

  -- Sin sesión de usuario (service role, tareas del servidor) no hay tope.
  if auth.uid() is null then
    return new;
  end if;

  -- El candado serializa las inserciones del mismo piloto en la misma tabla:
  -- sin él, varias en paralelo leerían el mismo conteo.
  perform pg_advisory_xact_lock(hashtextextended(tg_table_name || ':' || new.user_id::text, 0));

  -- Lo que ya salió de la ventana no cuenta y no hace falta guardarlo.
  delete from private.registro_de_inserciones
  where user_id = new.user_id and tabla = tg_table_name and en <= now() - v_ventana;

  -- Se cuenta en el registro y no en la tabla: borrar lo publicado no devuelve cupo.
  select count(*) into v_recientes
  from private.registro_de_inserciones
  where user_id = new.user_id and tabla = tg_table_name;

  if v_recientes >= v_maximo then
    raise exception 'demasiadas_publicaciones'
      using errcode = 'P0001', hint = format('Máximo %s cada %s.', v_maximo, v_ventana);
  end if;

  insert into private.registro_de_inserciones (tabla, user_id) values (tg_table_name, new.user_id);
  return new;
end
$$;
revoke all on function private.insercion_con_tope() from public;

-- ── 3 · Topes nuevos ───────────────────────────────────────────────────────

drop trigger if exists trg_tope_postulaciones on public.postulaciones;
create trigger trg_tope_postulaciones before insert on public.postulaciones
  for each row execute function private.insercion_con_tope('30', '1 day', 'sin_fecha');

